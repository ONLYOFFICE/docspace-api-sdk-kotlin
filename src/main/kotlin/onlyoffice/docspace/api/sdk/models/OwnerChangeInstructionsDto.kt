package onlyoffice.docspace.api.sdk.models


import com.squareup.moshi.Json
import com.squareup.moshi.JsonClass

/**
 * The outcome of asking for the portal-ownership transfer letter to be sent.
 *
 * @param status Whether the letter was sent: `1` that it was, `0` that the request was turned down. A refusal comes back  with HTTP 200, so this field and not the status code is what says whether anything happened - the request  is turned down when the caller is not the portal owner and when the named member is unknown or inactive.
 * @param message The outcome spelled out in the portal language. On success it names the address the letter went to, and it  carries an HTML `mailto:` anchor rather than plain text, so it has to be rendered as markup or stripped;  on a refusal it is the localised reason.
 */


data class OwnerChangeInstructionsDto (

    @Json(name = "status")
    val status: kotlin.Int? = null,

    @Json(name = "message")
    val message: kotlin.String? = null

) {


}

